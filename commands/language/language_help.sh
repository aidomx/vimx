#!/usr/bin/env bash

show_language_help() {
  echo ""
  echo -e "${YELLOW}Available commands:${NC}"
  echo -e "  ${GREEN}add${NC}      <language>  - Add new language (creates lang + ftdetect + syntax)"
  echo -e "  ${GREEN}scaffold${NC} <language>  - Interactive scaffold with ftdetect + syntax"
  echo -e "  ${GREEN}remove${NC}   <language>  - Remove language"
  echo -e "  ${GREEN}enable${NC}   <language>  - Enable disabled language"
  echo -e "  ${GREEN}disable${NC}  <language>  - Disable language"
  echo -e "  ${GREEN}list${NC}                 - List all languages"
  echo -e "  ${GREEN}info${NC}     <language>  - Show language info"
  echo -e "  ${GREEN}edit${NC}     <language>  - Open in editor"
  echo -e "  ${GREEN}help${NC}                 - Show help"
  echo -e "  ${GREEN}quit${NC}                 - Exit"
  echo ""
}

detail_language_help() {
  echo -e "${CYAN}vimx lang${NC} - Language manager and Interactive"
  echo ""
  echo -e "${WHITE}USAGE:${NC}"
  echo "  vimx lang <command>"
  echo ""
  echo -e "${WHITE}AVAILABLE COMMAND:${NC}"
  echo -e "  ${GREEN}add${NC}      <language>  - Add new language (auto-creates ftdetect + syntax)"
  echo -e "  ${GREEN}scaffold${NC} <language>  - Interactive scaffold with file extension & comment style"
  echo -e "  ${GREEN}remove${NC}   <language>  - Remove language"
  echo -e "  ${GREEN}enable${NC}   <language>  - Enable disabled language"
  echo -e "  ${GREEN}disable${NC}  <language>  - Disable language"
  echo -e "  ${GREEN}list${NC}                 - List all languages with ftdetect/syntax status"
  echo -e "  ${GREEN}info${NC}     <language>  - Show language info"
  echo -e "  ${GREEN}edit${NC}     <language>  - Open in editor"
  echo ""
  echo -e "${WHITE}EXAMPLES:${NC}"
  echo "  vimx lang add rust              # Quick add with defaults"
  echo "  vimx lang scaffold rust         # Interactive: pick extensions, comment style"
  echo "  vimx lang list                  # See all languages + ftdetect/syntax status"
  echo "  vimx lang info rust             # Show details for rust"
  echo ""
  echo -e "${WHITE}CUSTOM LANGUAGE SUPPORT:${NC}"
  echo "  Each language gets 3 files:"
  echo "    langs/<name>.vim     — Settings, indentation, keymaps"
  echo "    ftdetect/<name>.vim  — Filetype detection (*.rs → rust)"
  echo "    syntax/<name>.vim    — Syntax highlighting rules"
  echo ""
}
